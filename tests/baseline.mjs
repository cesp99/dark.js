// Runs the suite against the new build and against v1 (main:dark.js) in every browser and writes
// tests/BASELINE.md.   node tests/baseline.mjs [--browser=chromium,webkit]
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, startServer, loadScript, launch } from './lib.mjs';
import { runSuite } from './suite.mjs';

const arg = process.argv.find(a => a.startsWith('--browser='));
const browsers = arg ? arg.slice(10).split(',') : ['chromium', 'webkit'];
const variants = [['new', loadScript(false)], ['legacy', loadScript(true)]];

const { server, base } = await startServer();
const runs = []; // { browser, version, variant, results }
for (const name of browsers) {
  let browser;
  try { browser = await launch(name); } catch (e) {
    console.log(`${name}: could not launch — ${String(e.message).split('\n')[0]}`);
    continue;
  }
  for (const [variant, script] of variants) {
    const suite = await runSuite({ browser, browserName: name, script, label: variant, base });
    suite.summary();
    runs.push({ browser: name, version: browser.version(), variant, results: suite.results });
  }
  await browser.close();
}
server.close();

const esc = s => String(s || '').replace(/\|/g, '\\|');
const titles = runs.length ? runs[0].results.map(r => r.title) : [];
const label = r => `${r.browser[0].toUpperCase()}${r.browser.slice(1)} ${r.variant === 'new' ? 'v2' : 'v1'}`;
const lines = [
  '# Baseline: dark.js v2 vs v1',
  '',
  `Same suite (\`tests/suite.mjs\`) against the new build and against v1 (\`git show main:dark.js\`),`,
  `generated by \`npm run baseline\` on ${new Date().toISOString().slice(0, 10)}.`,
  'Scripts are injected like Eyed Out does it: at document start (`page.addInitScript`, the WKUserScript',
  'equivalent) unless a test says otherwise; the OS theme is Playwright\'s `colorScheme` emulation.',
  'Every check is judged from screenshot pixels, so both versions are measured the same way.',
  '',
  '| Browser | Engine | v2 | v1 |',
  '|---|---|---|---|',
];
for (const b of browsers) {
  const nu = runs.find(r => r.browser === b && r.variant === 'new');
  const old = runs.find(r => r.browser === b && r.variant === 'legacy');
  const score = r => r ? `${r.results.filter(x => x.ok).length}/${r.results.length}` : 'not run';
  lines.push(`| ${b} | ${nu ? nu.version : (old ? old.version : '—')} | ${score(nu)} | ${score(old)} |`);
}
lines.push('', '| Test | ' + runs.map(label).join(' | ') + ' |', '|---|' + runs.map(() => '---').join('|') + '|');
for (const t of titles) {
  const cells = runs.map(r => {
    const x = r.results.find(y => y.title === t);
    if (!x) return '—';
    return `${x.ok ? '✓' : '✗'}${x.note ? ` ${esc(x.note)}` : ''}`;
  });
  lines.push(`| ${esc(t)} | ${cells.join(' | ')} |`);
}
lines.push('');
const out = path.join(ROOT, 'tests/BASELINE.md');
const notes = fs.existsSync(path.join(ROOT, 'tests/BASELINE.notes.md')) ? fs.readFileSync(path.join(ROOT, 'tests/BASELINE.notes.md'), 'utf8') : '';
fs.writeFileSync(out, lines.join('\n') + (notes ? `\n${notes}` : ''));
console.log(`\nwrote ${path.relative(ROOT, out)}`);
